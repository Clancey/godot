- (void)applicationWillTerminate:(UIApplication *)application {
	if (_renderMode == GDTRenderModeCompositorServices) {
		// Termination is best-effort on UIKit. Never join an owner that may need
		// a main-actor UI call; persistence belongs to the earlier pause event.
		visionos_finish_engine();
		return;
	}
	[super applicationWillTerminate:application];
}

