		visionos_dispatch_to_engine(^{
			if (OS::get_singleton()->get_main_loop()) {
				OS::get_singleton()->get_main_loop()->notification(MainLoop::NOTIFICATION_OS_MEMORY_WARNING);
			}
		});
		return;
	}
	[super applicationDidReceiveMemoryWarning:application];
}

