- (void)notifyEngineEnteredBackground {
	// Give the queued pause notification a finite opportunity before suspension.
	__block UIBackgroundTaskIdentifier task = UIBackgroundTaskInvalid;
	void (^end_task)(void) = ^{
		if (task != UIBackgroundTaskInvalid) {
			[UIApplication.sharedApplication endBackgroundTask:task];
			task = UIBackgroundTaskInvalid;
		}
	};
	task = [UIApplication.sharedApplication beginBackgroundTaskWithName:@"Godot pause notification" expirationHandler:end_task];
	visionos_dispatch_to_engine(^{
		OS_AppleEmbedded::get_singleton()->on_enter_background();
		dispatch_async(dispatch_get_main_queue(), end_task);
	});
}

+ (BOOL)hasImmersiveScene {
	for (UIScene *scene in UIApplication.sharedApplication.connectedScenes) {
		if (is_immersive_scene(scene) && scene.activationState != UISceneActivationStateUnattached) {
			return YES;
		}
	}
	return NO;
}

